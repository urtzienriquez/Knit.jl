"""
    clean_aux(file; dry_run=false, quiet=false)

Remove the auxiliary files of a compilation (`.aux`, `.log`, `.bbl`, `.synctex.gz`...), keeping the
`.tex` and `.pdf`: only those latexmk recorded as generated by it (in `<base>.fdb_latexmk` and
`<base>.fls`), with those two files and the SyncTeX one. Unrelated files sharing the base name
(`<base>.jl`, `<base>.bib`), files elsewhere, folders and the label snapshot (`<base>-labels.aux`)
are never touched. As knitrmini's `clean_aux`. Returns the paths removed (or, with `dry_run`,
removable).
"""
function clean_aux(file::AbstractString; dry_run::Bool=false, quiet::Bool=false)
    dir = abspath(dirname(abspath(file)))
    base = first(splitext(basename(file)))
    fdb = joinpath(dir, base * ".fdb_latexmk")
    fls = joinpath(dir, base * ".fls")
    if !isfile(fdb) && !isfile(fls)
        quiet || println("No latexmk record ($(basename(fdb)) or $(basename(fls))) for $base; nothing removed.")
        return String[]
    end
    candidates = vcat(_fdb_generated(fdb), _fls_outputs(fls), basename.([fdb, fls]),
                      [base * ".synctex.gz", base * ".bbl-SAVE-ERROR"])
    own(p) = begin
        full = isabspath(p) ? p : joinpath(dir, p)
        name = basename(p)
        normpath(dirname(full)) == normpath(dir) && startswith(name, base * ".") &&
            !occursin(r"\.(tex|pdf|jnw|jl)$"i, name)
    end
    files = unique([joinpath(dir, basename(p)) for p in candidates if own(p)])
    files = [f for f in files if isfile(f)]
    dry_run || foreach(rm, files)
    if !quiet
        println(isempty(files) ? "No auxiliary files to remove for $base." :
                (dry_run ? "Would remove: " : "Removed: ") * join(basename.(files), ", "))
    end
    return files
end

function _fdb_generated(fdb::AbstractString)
    out = String[]
    isfile(fdb) || return out
    section = ""
    for line in eachline(fdb)
        if occursin(r"^\s*\(.*\)\s*$", line)
            section = strip(line)
        elseif startswith(line, "[")
            section = ""
        elseif section == "(generated)"
            m = match(r"\"([^\"]+)\"", line)
            m === nothing || push!(out, m.captures[1])
        end
    end
    return out
end

function _fls_outputs(fls::AbstractString)
    isfile(fls) || return String[]
    return [line[8:end] for line in eachline(fls) if startswith(line, "OUTPUT ")]
end
