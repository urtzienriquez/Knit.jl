# Package citations, as knitrmini's write_pkg_bib for R: a .bib with the entries of the packages a
# project uses (their CITATION.bib, the Julia convention) and of Julia itself, marked so that each
# knit refreshes it (and never creates one).

const PKG_BIB_MARKER = "% generated by Knit.jl"

const JULIA_CITATION = """
@article{Julia-2017,
  title = {Julia: A Fresh Approach to Numerical Computing},
  author = {Bezanson, Jeff and Edelman, Alan and Karpinski, Stefan and Shah, Viral B.},
  journal = {SIAM Review},
  volume = {59},
  number = {1},
  pages = {65--98},
  year = {2017},
  doi = {10.1137/141000671},
}"""

"""
    write_pkg_bib(file="packages.bib"; project=Base.active_project(), quiet=false)

Write the citations of the packages a project depends on (its `Project.toml`: each package's
`CITATION.bib`, when it has one) and of Julia, into `file`, marked as generated by Knit.jl: each
knit of a document in that folder then refreshes it. Returns the names of the packages cited.
"""
function write_pkg_bib(file::AbstractString="packages.bib"; project=Base.active_project(), quiet::Bool=false)
    deps = project === nothing || !isfile(project) ? String[] :
           sort(collect(keys(get(TOML.parsefile(project), "deps", Dict()))))
    entries = String[JULIA_CITATION]
    cited = String[]
    for name in deps
        path = Base.find_package(name)
        path === nothing && continue
        citation = joinpath(dirname(dirname(path)), "CITATION.bib")
        if isfile(citation)
            push!(entries, strip(read(citation, String)))
            push!(cited, name)
        end
    end
    write(file, PKG_BIB_MARKER * "\n\n" * join(entries, "\n\n") * "\n")
    quiet || println("Package citations: Julia", isempty(cited) ? "" : ", " * join(cited, ", "), " -> ", file)
    return cited
end

"""
    update_pkg_bib(dir; quiet=true)

Refresh the .bib files of a folder that Knit.jl wrote (they start with its marker); never creates one.
"""
function update_pkg_bib(dir::AbstractString; quiet::Bool=true)
    isdir(dir) || return
    for name in readdir(dir)
        endswith(name, ".bib") || continue
        path = joinpath(dir, name)
        first_line = open(io -> eof(io) ? "" : readline(io), path)
        startswith(first_line, PKG_BIB_MARKER) && write_pkg_bib(path; quiet)
    end
end
